// WHY: A static export cannot generate a service worker that knows the hashed
// asset names. This script walks the finished `out/` tree, writes a precache
// list and a small worker, and keeps every path relative so the same build
// works at the root and under the GitHub Pages project subpath.
// PACK: pwa-deploy
// 2026-10-23 opencode: created for the pwa-deploy pack [pack: pwa-deploy]

import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const output = join(here, "..", "out");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const full = join(directory, entry.name);
      if (entry.isDirectory()) return walk(full);
      if (entry.name.endsWith(".map")) return [];
      return [relative(output, full).split(sep).join("/")];
    }),
  );
  return files.flat();
}

function asUrl(file) {
  if (file === "index.html") return "./";
  if (file.endsWith("/index.html")) return `./${file.slice(0, -"index.html".length)}`;
  return `./${file}`;
}

try {
  await stat(join(output, "index.html"));
} catch {
  throw new Error("out/index.html is missing; run next build before build-pwa");
}

const skip = new Set(["sw.js", "404.html", "404/index.html", "_not-found/index.html"]);
const files = (await walk(output)).filter((file) => !skip.has(file)).sort();
const entries = files.map((file) => ({ file, url: asUrl(file) }));
const digest = createHash("sha256");
for (const entry of entries) {
  digest.update(entry.url);
  digest.update(await readFile(join(output, entry.file)));
}
const version = digest.digest("hex").slice(0, 16);
const precache = entries.map((entry) => entry.url);

const worker = `// Generated by scripts/build-pwa.mjs. Do not edit by hand.
const VERSION = "flashcards:" + self.registration.scope + ":${version}";
const PREFIX = "flashcards:" + self.registration.scope + ":";
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const SHELL = new URL("./", self.location.href).href;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(VERSION).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(PREFIX) && key !== VERSION)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

async function cacheFirst(request) {
  const hit = await caches.match(request);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok) {
    const cache = await caches.open(VERSION);
    await cache.put(request, response.clone());
  }
  return response;
}

async function networkFirst(request) {
  try {
    const response = await fetch(request);
    if (response.ok) {
      const cache = await caches.open(VERSION);
      await cache.put(request, response.clone());
    }
    return response;
  } catch {
    const hit = await caches.match(request);
    if (hit) return hit;
    const shell = await caches.match(SHELL);
    if (shell) return shell;
    return new Response("Offline", {
      status: 503,
      headers: { "Content-Type": "text/plain" },
    });
  }
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    event.respondWith(networkFirst(request));
    return;
  }
  event.respondWith(cacheFirst(request));
});
`;

await writeFile(join(output, "sw.js"), worker);
console.log(`wrote out/sw.js (${precache.length} files, version ${version})`);
